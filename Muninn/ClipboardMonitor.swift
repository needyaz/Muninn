import AppKit
import Combine

@Observable
class ClipboardMonitor {
    private var timer: Timer?
    private var lastChangeCount: Int
    private var selfCopyChangeCount: Int?
    private let historyStore: HistoryStore
    private let excludedAppsStore: ExcludedAppsStore
    private let excludedTypesStore: ExcludedTypesStore
    private let settingsStore: SettingsStore
    private let statsStore: StatsStore

    var isPaused = false
    var pauseResumeDate: Date?
    private var pauseTimer: Timer?

    private var lastScreenshotChangeCount: Int?
    private var lastScreenshotFilename: String?

    func noteScreenshot(changeCount: Int, filename: String?) {
        lastScreenshotChangeCount = changeCount
        lastScreenshotFilename = filename
    }

    init(historyStore: HistoryStore, excludedAppsStore: ExcludedAppsStore, excludedTypesStore: ExcludedTypesStore, settingsStore: SettingsStore, statsStore: StatsStore) {
        self.historyStore = historyStore
        self.excludedAppsStore = excludedAppsStore
        self.excludedTypesStore = excludedTypesStore
        self.settingsStore = settingsStore
        self.statsStore = statsStore
        self.lastChangeCount = NSPasteboard.general.changeCount
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            self?.poll()
        }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func didSelfCopy() {
        selfCopyChangeCount = NSPasteboard.general.changeCount
    }

    // MARK: - Pause / Resume

    func pause(for duration: TimeInterval?) {
        isPaused = true
        pauseTimer?.invalidate()
        pauseTimer = nil

        if let duration {
            pauseResumeDate = Date().addingTimeInterval(duration)
            pauseTimer = Timer.scheduledTimer(withTimeInterval: duration, repeats: false) { [weak self] _ in
                self?.resume()
            }
        } else {
            pauseResumeDate = nil
        }
    }

    func resume() {
        isPaused = false
        pauseResumeDate = nil
        pauseTimer?.invalidate()
        pauseTimer = nil
        // Re-sync change count so we don't capture stale clipboard content
        lastChangeCount = NSPasteboard.general.changeCount
    }

    // MARK: - Polling

    private func poll() {
        guard !isPaused else { return }

        let pasteboard = NSPasteboard.general
        let current = pasteboard.changeCount

        guard current != lastChangeCount else { return }
        lastChangeCount = current

        // Skip if this was our own copy
        if let selfCount = selfCopyChangeCount, selfCount == current {
            selfCopyChangeCount = nil
            return
        }
        selfCopyChangeCount = nil

        // Capture source app bundle ID and screenshot filename
        let sourceAppBundleID: String?
        let screenshotFilename: String?
        if current == lastScreenshotChangeCount {
            sourceAppBundleID = "com.apple.Screenshot"
            screenshotFilename = lastScreenshotFilename
            lastScreenshotChangeCount = nil
            lastScreenshotFilename = nil
        } else {
            sourceAppBundleID = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
            screenshotFilename = nil
        }

        // Skip if frontmost app is excluded
        if let bundleID = sourceAppBundleID,
           excludedAppsStore.isExcluded(bundleID) {
            return
        }

        let types = pasteboard.types ?? []

        // Check for sensitive/concealed content (password managers, etc.)
        let isSensitive = types.contains(NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
            || types.contains(NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))

        if isSensitive {
            switch settingsStore.sensitiveHandling {
            case "skip":
                return
            case "mask":
                // Record with actual value but flag as sensitive (preview is masked)
                let id = UUID()
                let string = pasteboard.string(forType: .string)
                let item = HistoryItem(
                    id: id,
                    value: string,
                    contentType: .text,
                    sourceAppBundleID: sourceAppBundleID,
                    isSensitive: true
                )
                historyStore.add(item)
                didCapture(contentType: .text, sourceApp: sourceAppBundleID)
                return
            default:
                break // "allow" — fall through to normal processing
            }
        }

        let id = UUID()

        // 1. File URLs
        if types.contains(.fileURL),
           let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: nil) as? [URL],
           !urls.isEmpty {
            guard !excludedTypesStore.isExcluded(.fileURL) else { return }
            let paths = urls.map { $0.path }

            // Save file data as blob so export/import preserves the actual content
            var blobFile: String?
            if urls.count == 1, let data = try? Data(contentsOf: urls[0]) {
                let ext = urls[0].pathExtension.isEmpty ? "dat" : urls[0].pathExtension
                blobFile = BlobStorage.save(data, id: id, ext: ext)
            }

            let item = HistoryItem(
                id: id,
                contentType: .fileURL,
                blobFile: blobFile,
                fileURLs: paths,
                sourceAppBundleID: sourceAppBundleID
            )
            historyStore.add(item)
            if settingsStore.enablePDFTextExtraction,
               urls.count == 1,
               urls[0].pathExtension.lowercased() == "pdf",
               let blob = blobFile,
               let data = BlobStorage.load(blob) {
                historyStore.beginScanning(id: id)
                PDFTextService.extractText(from: data) { [weak historyStore] text in
                    historyStore?.endScanning(id: id)
                    guard let text else { return }
                    historyStore?.update(id: id, ocrText: text)
                }
            }
            didCapture(contentType: .fileURL, sourceApp: sourceAppBundleID)
            return
        }

        // 2. Image (PNG or TIFF)
        if types.contains(.png) || types.contains(.tiff) {
            guard !excludedTypesStore.isExcluded(.image) else { return }
            let imageData: Data?
            if types.contains(.png) {
                imageData = pasteboard.data(forType: .png)
            } else {
                imageData = pasteboard.data(forType: .tiff)
            }
            if let data = imageData {
                let ext = types.contains(.png) ? "png" : "tiff"
                let blobFile = BlobStorage.save(data, id: id, ext: ext)
                let item = HistoryItem(
                    id: id,
                    value: screenshotFilename,
                    contentType: .image,
                    blobFile: blobFile,
                    sourceAppBundleID: sourceAppBundleID
                )
                historyStore.add(item)
                if settingsStore.enableOCR {
                    historyStore.beginScanning(id: id)
                    OCRService.extractText(from: data) { [weak historyStore] text in
                        historyStore?.endScanning(id: id)
                        guard let text else { return }
                        historyStore?.update(id: id, ocrText: text)
                    }
                }
                if settingsStore.enableQRDetection {
                    historyStore.beginScanning(id: id)
                    QRService.detectBarcode(from: data) { [weak historyStore] value in
                        historyStore?.endScanning(id: id)
                        guard let value else { return }
                        historyStore?.update(id: id, detectedBarcode: value)
                    }
                }
                didCapture(contentType: .image, sourceApp: sourceAppBundleID)
                return
            }
        }

        // 3. PDF
        if types.contains(.pdf) {
            guard !excludedTypesStore.isExcluded(.pdf) else { return }
            if let data = pasteboard.data(forType: .pdf) {
                let blobFile = BlobStorage.save(data, id: id, ext: "pdf")
                let item = HistoryItem(
                    id: id,
                    contentType: .pdf,
                    blobFile: blobFile,
                    sourceAppBundleID: sourceAppBundleID
                )
                historyStore.add(item)
                if settingsStore.enablePDFTextExtraction {
                    historyStore.beginScanning(id: id)
                    PDFTextService.extractText(from: data) { [weak historyStore] text in
                        historyStore?.endScanning(id: id)
                        guard let text else { return }
                        historyStore?.update(id: id, ocrText: text)
                    }
                }
                didCapture(contentType: .pdf, sourceApp: sourceAppBundleID)
                return
            }
        }

        // 4. Color
        if types.contains(.color) {
            guard !excludedTypesStore.isExcluded(.color) else { return }
            if let data = pasteboard.data(forType: .color),
               let color = try? NSKeyedUnarchiver.unarchivedObject(ofClass: NSColor.self, from: data) {
                let c = color.usingColorSpace(.sRGB) ?? color
                let components = [
                    Double(c.redComponent),
                    Double(c.greenComponent),
                    Double(c.blueComponent),
                    Double(c.alphaComponent)
                ]
                let item = HistoryItem(
                    id: id,
                    contentType: .color,
                    colorComponents: components,
                    sourceAppBundleID: sourceAppBundleID
                )
                historyStore.add(item)
                didCapture(contentType: .color, sourceApp: sourceAppBundleID)
                return
            }
        }

        // 5. Text (with optional rich text blob)
        if let string = pasteboard.string(forType: .string) {
            guard !excludedTypesStore.isExcluded(.text) else { return }
            let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !trimmed.isEmpty else { return }

            var blobFile: String?
            // Save RTF blob if present for faithful paste-back
            if let rtfData = pasteboard.data(forType: .rtf) {
                blobFile = BlobStorage.save(rtfData, id: id, ext: "rtf")
            } else if let htmlData = pasteboard.data(forType: .html) {
                blobFile = BlobStorage.save(htmlData, id: id, ext: "html")
            }

            let item = HistoryItem(
                id: id,
                value: string,
                contentType: .text,
                blobFile: blobFile,
                sourceAppBundleID: sourceAppBundleID
            )
            historyStore.add(item)
            didCapture(contentType: .text, sourceApp: sourceAppBundleID)
        }
    }

    private func didCapture(contentType: ClipboardContentType, sourceApp: String?) {
        if settingsStore.enableStats {
            statsStore.recordCapture(contentType: contentType, sourceApp: sourceApp)
        }
        if !settingsStore.captureSound.isEmpty {
            NSSound(named: NSSound.Name(settingsStore.captureSound))?.play()
        }
    }
}
